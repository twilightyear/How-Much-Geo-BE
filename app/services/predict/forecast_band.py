#예측 오차 띠 — 준공 정산을 값 하나가 아니라 범위로 내기 위한 폭
#  뜻 : 지금 코드의 예측 방식으로 과거의 어느 시점에서 h 년 뒤를 맞혀 봤을 때, 실제 값이 예측에서 벗어난 비율의 절대값 중앙값.
#       "과거 같은 기간의 예측 가운데 절반은 이 폭 안에 들어왔다" 는 뜻이다
#  방법 : 그 시점까지의 자료만으로 연율을 구해 h 년 뒤를 예측하고 실제 지수와 비교 (2026-11-29 측정)
#    공사비 = 건설공사비지수(주거용건물) 20년 창 로그선형회귀 연율 — trend.estimate_annual_rate 와 같은 식
#             기준일 2010 ~ 2025년 매월 (1년 뒤 189개 ~ 7년 뒤 117개)
#    분양가 = 노원구 아파트 실거래가지수, 20년 창 연율에서 공사비 장기 연율로 5년 동안 수렴 — sale_price.escalate 와 같은 식
#             기준일 2014 ~ 2025년 매 분기 (1년 뒤 47개 ~ 7년 뒤 23개)
#  한계
#    7년을 넘는 기간은 기준일이 20개 아래로 줄어 재지 않았다 → 7년 값을 그대로 쓴다 (실제 불확실성은 더 크다)
#    분양가의 과거 오차는 대부분 "실제가 예측보다 높은" 쪽이었다 (2017 ~ 2021년 상승기가 기준일 대부분에 걸린다).
#      방향은 시기에 따라 달라지므로 크기만 쓰고 위아래 같은 폭으로 둔다
#    공사비 띠는 지수 예측의 오차만 잰 것이다. 계약 단가가 지수보다 더 오르는 몫(비물가 초과 증액)의 불확실성은 들어 있지 않다
#  측정 스크립트 : ~/Howmuch_GEO/참고자료/측정_2026-11-29/band_backtest.py (저장소 밖)

#h 년 뒤 예측의 절대 오차 중앙값 (비율)
COST_BAND = {1: 0.019, 2: 0.037, 3: 0.058, 4: 0.074, 5: 0.083, 6: 0.094, 7: 0.095}
SALE_BAND = {1: 0.058, 2: 0.162, 3: 0.236, 4: 0.283, 5: 0.328, 6: 0.408, 7: 0.432}
BANDS = {"cost": COST_BAND, "sale": SALE_BAND}

BASIS = (
    "관리처분 이후의 일반분양가 또는 공사비가 과거 예측 오차의 중앙값만큼 빗나간 경우 (각각 따로 계산) "
    "(건설공사비지수 2010~2025년, 노원구 아파트 실거래가지수 2014~2025년 기준일로 측정)"
)

#years 년 뒤 예측의 오차 폭 (0년 = 0, 표 사이는 직선 보간, 표를 넘으면 마지막 값)
def band(kind: str, years: float) -> float:
    table = BANDS[kind]
    if years <= 0:
        return 0.0
    last = max(table)
    if years >= last:
        return table[last]
    lower = int(years)
    low = table.get(lower, 0.0)
    high = table[lower + 1]
    return low + (high - low) * (years - lower)
